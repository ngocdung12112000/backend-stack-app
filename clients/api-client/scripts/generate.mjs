// Generates src/generated/* from every OpenAPI document in contracts/openapi/<service>.json.
// One typed openapi-fetch client per service, all behind one base URL (the gateway).
import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const specDir = join(root, "..", "..", "contracts", "openapi");
const outDir = join(root, "src", "generated");

const services = readdirSync(specDir)
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.slice(0, -".json".length))
  .sort();

if (services.length === 0) {
  throw new Error(`No OpenAPI documents found in ${specDir}`);
}

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const pascal = (s) => s.replace(/(^|[-_])(\w)/g, (_, __, c) => c.toUpperCase());
const bin = join(root, "node_modules", "openapi-typescript", "bin", "cli.js");

for (const svc of services) {
  execFileSync(process.execPath, [bin, join(specDir, `${svc}.json`), "-o", join(outDir, `${svc}.ts`)], {
    stdio: "inherit",
  });
}

const typeExports = services
  .map((s) => `export type { paths as ${pascal(s)}Paths, components as ${pascal(s)}Components } from "./${s}.js";`)
  .join("\n");

const imports = services.map((s) => `import type { paths as ${pascal(s)}Paths } from "./${s}.js";`).join("\n");
const members = services.map((s) => `    ${s}: createClient<${pascal(s)}Paths>(options),`).join("\n");
const merged = services.map((s) => `${pascal(s)}Paths`).join(" & ");

writeFileSync(
  join(outDir, "client.ts"),
  `// GENERATED by scripts/generate.mjs. Do not edit.
import createClient, { type ClientOptions, type Middleware } from "openapi-fetch";
${imports}

${typeExports}

/** RFC 7807 problem details returned by every service; \`code\` is service-prefixed (e.g. CATALOG_NOT_FOUND). */
export interface ProblemDetails {
  type?: string;
  title?: string;
  status?: number;
  detail?: string;
  instance?: string;
  code?: string;
  traceId?: string;
  errors?: Record<string, string[]>;
  [key: string]: unknown;
}

/** Every service's paths merged: the gateway exposes them all under one base URL. */
export type GatewayPaths = ${merged};

export interface StackShopClientOptions extends Omit<ClientOptions, "baseUrl"> {
  /** Gateway URL, e.g. http://localhost:5000 */
  baseUrl: string;
  /** Optional bearer token provider; called per request. */
  getAccessToken?: () => string | null | undefined | Promise<string | null | undefined>;
}

/** Single flat typed client over the gateway (paths merged across services). */
export function createStackShopClient({ getAccessToken, ...options }: StackShopClientOptions) {
  const client = createClient<GatewayPaths>(options);
  if (getAccessToken) {
    const auth: Middleware = {
      async onRequest({ request }) {
        const token = await getAccessToken();
        if (token) request.headers.set("Authorization", \`Bearer \${token}\`);
        return request;
      },
    };
    client.use(auth);
  }
  return client;
}

export type StackShopClient = ReturnType<typeof createStackShopClient>;

/** Per-service typed clients (kept for callers that want one client per service). baseUrl is the gateway URL. */
export function createApiClient(options: ClientOptions) {
  return {
${members}
  };
}

export type ApiClient = ReturnType<typeof createApiClient>;
`,
);

console.log(`Generated client for: ${services.join(", ")}`);
